# 字段：唯一来源
# ============================================================

#: 章蓝图（Chapter.goal）的字段，顺序即推荐书写顺序
CHAPTER_BLUEPRINT_FIELDS: tuple[str, ...] = (
    "章核心", "因果链", "情绪走向", "结尾钩", "角色侧重", "主题浸染",
)

#: 场景蓝图（Scene.summary）写前的字段：这是一场戏的创作计划
SCENE_BLUEPRINT_FIELDS: tuple[str, ...] = (
    "目标", "因果链", "关键信息", "结尾状态", "本场基调",
)

#: 场景蓝图写完正文后的字段：计划态字段被替换成事实档案，不是叠加
SCENE_FACT_FIELDS: tuple[str, ...] = (
    "本场", "关键信息", "结尾状态", "痕迹", "原意图",
)

#: 蓝图里不允许出现的措辞：它们是写给作者的话（评价 / 表演 / 指导），不是故事内容。
#: 长词在前，避免「必须让读者」与「让读者」重复命中。
BANNED_IN_BLUEPRINT: tuple[str, ...] = (
    "必须让读者", "让读者", "要有画面感", "要写出", "情绪高点", "反差萌",
    "仪式感", "笑点", "爆点", "拉满", "引擎", "高光", "实锤", "拍大腿",
)


def _field_line(fields: tuple[str, ...]) -> str:
    return "".join(f"【{f}】" for f in fields)


def chapter_hint() -> str:
    """章蓝图的一句话说明（工具参数描述用，短）。"""
    return (
        "章节蓝图（章级创作计划：" + _field_line(CHAPTER_BLUEPRINT_FIELDS) + "）。"
        "只写事件与状态、用「A → B」写因果，不写镜头 / 台词 / 评价性措辞；"
        "字段含义见系统提示的《创作蓝图规范》"
    )


def scene_hint() -> str:
    """场景蓝图的一句话说明（工具参数描述用，短）。"""
    return (
        "场景蓝图（本场创作计划：" + _field_line(SCENE_BLUEPRINT_FIELDS) + "）。"
        "只写事件与状态、用「A → B」写因果，不写镜头 / 台词措辞 / 评价性措辞；"
        "字段含义见系统提示的《创作蓝图规范》"
    )


# ============================================================
# 规范正文
# ============================================================

_HEADER = """\
# --- 创作蓝图规范（写蓝图前必读） ---
蓝图是**写之前的约束清单**：规定必须发生什么、结束时处于什么状态；不规定用什么句子写出来。
一句话判据：**这句话是「必须发生」还是「可以这样写」？前者进蓝图，后者是正文的事。**"""

_GRAIN = """\
## 只用三种粒度
- **事件级**：谁做了什么决定 / 知道了什么 / 关系或局势发生了什么变化（主谓宾，不写动作序列）
- **状态级**：结束时人物与局势处于什么状态（下一场从这里接力）
- **意图级**：本场在情绪与主题上的功能（一句话软约束，实现方式自由）"""

_ARROW = """\
## 剧情用箭头写：A → B
- 因果链是蓝图的最小单位：左边是触发（谁做了什么、发生了什么），右边是结果（谁改变了、
  局面变成什么样），写成「A → B」。
- 只写关键转折（章 2-4 条、场 2-4 条）；不写每一步动作，不写「然后…然后…」的流水账。
- 找不出关键因果的场次宁可少写一条，也不要拿动作凑数。"""

CHAPTER_SPEC = """\
## 章蓝图（Chapter.goal）—— 写之前定这一章推进什么
【章核心】1 句：谁做了什么决定 / 局面变成什么样（不写过程）
【因果链】2-4 条「A → B」：本章的关键转折，每条只写触发与结果
【情绪走向】一句话：开头 → 中段 → 结尾（参考项，实现方式自由）
【结尾钩】章末留下的局面或悬念，下一章从哪里接
【角色侧重】本章重点出场的角色，以及他们做出的选择 / 发生的变化
【主题浸染】本章如何体现主题命题（1 句）"""

SCENE_SPEC = """\
## 场景蓝图（Scene.summary）—— 写之前定这一场演什么
【目标】1 句：本场在剧情 / 角色 / 主题上必须达成的推进
【因果链】2-4 条「A → B」：本场的关键转折（事件级，不写镜头与台词措辞）
【关键信息】必须留下的硬事实：数字锚点、规则、物品、位置、伤势、谁知道什么；
            需要一字不差的台词才在这里标「原句」，其余台词留给正文
【结尾状态】结束时人物与局势的状态，以及留给下一场的接口
【本场基调】一句话：本场在情绪 / 氛围上的取向（参考项，实现方式自由）"""

SYNC_SPEC = """\
## 回写：把场景蓝图改写成「事实档案」（Scene.summary）
正文是唯一事实来源。计划态字段（【目标】【因果链】【本场基调】）不再保留 ——
事实档案是**替换**，不是叠加；它同时是未来所有「只读蓝图不读正文」的读取依据。
【本场】2-4 条「A → B」：正文里**实际发生**的关键转折（不是原本打算写的）
【关键信息】正文里确立的硬事实：数字、规则、物品、身份、谁知道什么；对白仅在需要
            一字不差时以「原句」标注
【结尾状态】结束时人物与局势的实际状态（下一场从这里接力）
【痕迹】留下的伏笔 / 未解决的问题 / 悬置的疑问
【原意图】一句话：仅当实际内容与原本的计划有偏差时保留，说明原计划是什么"""

_BANNED = """\
## 绝不写进蓝图（写了就等于替正文做了决定）
- 镜头与动作序列（「掏出小本本记账」「把玩茶杯，嘴角勾起」）
- 台词原句（除【关键信息】里标了「原句」的）、比喻、吐槽、内心 OS 的具体措辞
- 评价性 / 表演性措辞：笑点、爆点、拉满、仪式感、反差萌、情绪高点、让读者、要写出…感
- 同一件事说三遍（【目标】讲过的不在【因果链】【关键信息】里再讲一遍）
- 备选方案（「或…」）与内部编号（S4、T2 之类）
- 否定式的边界（「不出现 X」「不揭示 Y」「不推进某线」）：蓝图没写到的线自然不会进正文，
  写成否定句反而会诱导正文去提到它 —— 边界靠「只写该写的」表达，不靠否定清单"""

_SELF_CHECK = """\
## 写完自检三问
1. 这句话是**事件**还是**镜头**？镜头 → 删。
2. 这句是「必须发生」还是「建议怎么写」？建议 → 删，或降进【本场基调】。
3. 有没有两处说了同一件事？→ 合并。"""

_SELF_CHECK_SYNC = """\
## 写完自检两问
1. 这条是正文里**真发生的**，还是我原本打算写的？打算写但没写 → 不进事实档案。
2. 这句是**事件 / 状态**还是**镜头 / 措辞**？后者 → 删。"""


def render_spec(kind: str = "all") -> str:
    """渲染蓝图规范文本。

    kind:

    * ``"all"``     —— 主循环用（章蓝图 + 场景蓝图）
    * ``"chapter"`` —— 素材建项目的结构规划
    * ``"scene"``   —— 素材建项目的场景规划
    * ``"sync"``    —— 场景蓝图回写（事实档案）
    """
    if kind == "chapter":
        parts = [_HEADER, _GRAIN, _ARROW, CHAPTER_SPEC, _BANNED, _SELF_CHECK]
    elif kind == "scene":
        parts = [_HEADER, _GRAIN, _ARROW, SCENE_SPEC, _BANNED, _SELF_CHECK]
    elif kind == "sync":
        parts = [_HEADER, SYNC_SPEC, _ARROW, _BANNED, _SELF_CHECK_SYNC]
    else:
        parts = [_HEADER, _GRAIN, _ARROW, CHAPTER_SPEC, SCENE_SPEC, _BANNED, _SELF_CHECK]
    return "\n\n".join(parts)


def lint(text: str) -> list[str]:
    """返回蓝图里不该出现的措辞（空列表 = 通过）。"""
    text = text or ""
    hits: list[str] = []
    for word in BANNED_IN_BLUEPRINT:
        if word in text and not any(word in h for h in hits):
            hits.append(word)
    return hits


def lint_note(text: str) -> str:
    """给模型的回执提示：蓝图里出现了评价性措辞时建议改写。通过则返回空串。"""
    hits = lint(text)
    if not hits:
        return ""
    return (
        "蓝图里出现了评价性 / 表演性措辞（" + "、".join(hits) + "）——那是写给作者的话，"
        "不是故事内容。请按《创作蓝图规范》改写成事件与状态（例如「A → B」），"
        "不要用「笑点」「拉满」这类词来交代意图。"
    )