"""章蓝图（「本章要写什么」）写法说明的唯一来源。

蓝图是**动笔之前写给写作者自己的一张字条**：说清这一章要写什么。
它不求全、不列字段、不检查措辞——写成一段连贯的话即可。

规格集中在这里，供所有会写蓝图或读蓝图的地方共用：

* 主循环系统提示（``loop.py`` 注入）—— 对话 / 协写模式写蓝图时看的就是它
* 素材建项目模板（``material_structure``）
* 各工具的参数描述（``create_chapter`` / ``update_chapter``）

任何一处需要写法规则时都从这里取，避免同一份规格散落多处后彼此漂移
（历史上 ``update_chapter`` 就漏过整份字段名）。

**没有场景蓝图了**：章是最底层，也是正文层。章蓝图说这一章整体从哪走到哪，
章内自然分几段，不再先写"场景卡"再拼。
"""
from __future__ import annotations

# ============================================================
# 工具参数描述（一句话）
# ============================================================


def chapter_hint() -> str:
    """章蓝图（「本章要写什么」）的一句话说明（工具参数描述用）。"""
    return (
        "本章要写什么：用一段话概括这一章——谁想要什么、发生哪些事、"
        "事情怎么一步步走到章末、章末停在什么处境。"
        "章内不必逐场列出，也不写「怎么写得好看」"
    )


# ============================================================
# 说明正文
# ============================================================

_HEADER = """\
# --- 章蓝图（本章要写什么）---
蓝图是**你动笔之前写给自己的字条**：说清这一章要写什么。
它不是清单，不用凑字段，不必写成条目——像你给朋友讲这一章会怎么演那样写。"""

_WHAT = """\
## 把这一章要写的内容概括清楚
写成一段连贯的话，像你先给朋友把这一章讲一遍：听完他就知道你打算写什么。
- **谁**在这件事里，他此刻**想要什么**（或处在什么处境）
- **发生了哪些事**：重要的推进与转折都要交代到——不是只写一个转折；但也不必把每一步动作、
  每句对话都列出来
- 结束时**谁变了、局面变成什么样**；这里如果要留扣子，把扣子说一句

这是自然的先后顺序，不是三个栏目，中间不要加小标题。想不出「想要什么」就跳过；
不是每一章都需要钩子。"""

_LENGTH = """\
## 长度
不设字数，**但写成一段话就够了**：不分段、不加小标题。这一章有几件事要交代，
就写多长——按内容走，不按字数走。
只写「发生了什么事」，不用写「怎么演」（屋里怎么布置、人物什么表情、心里怎么想）——
那些留给你动笔的时候。另外别只写一句话：一句话交代不清这一章要演什么，写到那儿就得
临场编，这正是蓝图要避免的。"""

_RULE = """\
## 唯一需要守住的一条
**这句话说的是「发生什么」，还是「该怎么写得好看」？**
- 「他知道有人要杀他」→ 发生什么 → 写进蓝图
- 「这里要有画面感」「情绪拉满」「让读者拍大腿」→ 怎么写得好看 → 留给正文

蓝图只管必须发生什么，不管用什么句子写。"""

_EX_CHAPTER = """\
## 例子

**好**：
陈默回镇上办父亲的后事，本想两三天就走，行李都没怎么打开。头一晚守灵，来上香的邻居一个比一个
面生，话里话外都在试他这些年在外面做什么，他随口应付过去。第二天他在老宅翻父亲的旧抽屉，
翻出一本记着人名的账本，中间有几页被撕掉了；他拿着账本去问姑妈，姑妈先推说不知道，
后来又改口说「那笔钱早还清了」。傍晚他去镇上唯一还在营业的杂货铺买烟，老板认出他，
第一句话是「你还敢回来」。这一章结束在他坐在父亲坟前把这些碎片拼起来：当年那笔没人敢提的债
牵连着镇上不少人，有人不想他回来——他改了回程的车票，决定留下查清楚。"""

_LEGACY = """\
（库里已有的旧蓝图如果还带着【】字段名——那是更早的写法——按内容理解即可，不用改写它们。）"""


def render_guide(kind: str | None = None) -> str:
    """渲染章蓝图写法说明（主循环与素材建项目共用同一份）。

    ``kind`` 已废弃——只有一种蓝图了（章蓝图）。保留形参只是为了兼容
    仍在改造中的调用点，传什么都不影响返回值。
    """
    return "\n\n".join([_HEADER, _WHAT, _LENGTH, _RULE, _EX_CHAPTER, _LEGACY])
