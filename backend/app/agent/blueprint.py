"""创作蓝图（章蓝图 / 场景蓝图）规范的唯一来源。

蓝图是**写之前的约束清单**：它规定「必须发生什么、结束时处于什么状态」，不规定
「用什么句子写出来」。规格集中在这里，供所有会写蓝图或读蓝图的地方共用：

* 主循环系统提示（``loop.py`` 注入）—— 对话 / 协写模式写蓝图时看的就是它
* 素材建项目模板（``material_structure`` / ``material_scenes``）
* 场景蓝图的回写模板（``scene_sync``）与各工具的参数描述

任何一处需要字段名或写法规则时都从这里取，测试再断言各处一致，避免同一份规格
散落七八处后彼此漂移（历史上 ``update_chapter`` 就漏过整份字段名）。
"""
from __future__ import annotations

